export function getOptionHelp(field: SettingKey, value: string): OptionHelp {
  const known =
    optionHelp[field][value] ??
    (field === "colorTone"
      ? optionHelp[field][value.split("：")[0]]
      : undefined);
  return (
    known ??
    help(
      "这是你输入的自定义方向。会结合本轮场景与其他设置落实，不擅自替换你的要求。",
      value.replace(/^自定义：/, ""),
      "示例只展示你的原文；最终会按场景展开为完整描述。",
    )
  );
}
