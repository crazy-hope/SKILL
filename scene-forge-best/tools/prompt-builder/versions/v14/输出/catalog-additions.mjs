export function expandCatalog(topics, categories) {
  for (const [name, rows] of Object.entries(additions)) {
    const topic = topics[name];
    rows.split('\n').forEach((row, i) => {
      const category = categories[i];
      topic.categories[category] = [...new Set([...(topic.categories[category] || []), ...row.split('|')])];
    });
  }
  for (const [name, groups] of Object.entries(special)) {
    for (const [category, items] of Object.entries(groups)) {
      topics[name].categories[category] = [...new Set([...(topics[name].categories[category] || []), ...items])];
    }
  }
  for (const topic of Object.values(topics)) topic.elements = [...new Set(Object.values(topic.categories).flat())];
}
