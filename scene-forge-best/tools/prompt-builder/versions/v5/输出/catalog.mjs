export const ALIASES={'东方天界':'东方天界幻想','自然写实':'山川荒野','古代生活':'古代市井','太空科幻':'太空探索'};
const SEARCH_CONTEXT=new Map();
for(const [name,topic] of Object.entries(TOPICS)){
 const aliases=Object.keys(ALIASES).filter(alias=>ALIASES[alias]===name);
 const context=[name,topic.group,...aliases].join(' ');
 for(const item of [name,...topic.scene,...topic.elements])SEARCH_CONTEXT.set(item,(SEARCH_CONTEXT.get(item)||'')+' '+context);
}
export function resolveTopic(name){const key=ALIASES[name]||name;return Object.hasOwn(TOPICS,key)?TOPICS[key]:null;}
export function catalogGroups(field,names=[],scene=''){
 if(field==='题材')return [...new Set(Object.values(TOPICS).map(t=>t.group))].map(group=>[group,Object.keys(TOPICS).filter(name=>TOPICS[name].group===group)]);
 const entries=[...new Set(names.map(resolveTopic).filter(Boolean))];
 if(field==='想画什么')return entries.map(t=>[Object.keys(TOPICS).find(name=>TOPICS[name]===t),t.scene]);
 if(field!=='必须包含')return [];
 let priority=[];
 if(/肖像|人物|仙女|剑客|法师|骑士|乐师|书生|服装/.test(scene))priority.push('人物与身份','服装与配饰','工具与器物');
 if(/车站|列车|轨道|渡口|码头|港口|通勤|对接/.test(scene))priority.push('道路与交通设施','载具','信息与标识','能源与基础设施');
 if(/赛车|摩托|载具|飞船|飞艇|潜水器/.test(scene))priority.push('载具','工具与器物','能源与基础设施');
 if(/建筑|殿阁|宫阙|庭院|古堡|城墙|书院/.test(scene))priority.push('建筑与场所','道路与交通设施','自然环境');
 if(/森林|生态|动物|生物|山川|湖泊|荒野|冰川|珊瑚/.test(scene))priority.push('自然环境','生物与伙伴');
 const order=[...new Set([...priority,...CATEGORIES])];
 return order.map(category=>[category,[...new Set(entries.flatMap(t=>t.categories[category]||[]))]]).filter(g=>g[1].length);
}
export function filterGroups(groups,query='',category=''){
 const words=query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
 return groups.filter(([label])=>!category||label===category).map(([label,items])=>[label,items.filter(item=>words.every(word=>(label+' '+item+' '+(SEARCH_CONTEXT.get(item)||'')).toLocaleLowerCase().includes(word)))]).filter(g=>g[1].length);
}
